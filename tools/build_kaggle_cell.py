"""Bundle src/medsg into ONE self-contained Kaggle cell for a given stage.

Usage:  python tools/build_kaggle_cell.py stage1_measure [--setup setup.sh] > kaggle/cell_stage1.py
The generated cell writes the package to /kaggle/working/src, runs optional shell
setup lines, then runs the stage module. Paste it into a single Kaggle code cell.
"""
from __future__ import annotations

import argparse
import base64
import io
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TEMPLATE = '''# === medsg {stage}: auto-generated by tools/build_kaggle_cell.py — do not edit by hand ===
import base64, io, os, subprocess, sys, zipfile
SRC = "/kaggle/working/src"
zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(SRC)
sys.path.insert(0, SRC)
SETUP = {setup!r}
for line in SETUP:
    print("+", line, flush=True)
    subprocess.run(line, shell=True, check=True)
r = subprocess.run([sys.executable, "-u", "-m", "medsg.stages.{stage}"] + {args!r},
                   env={{**os.environ, "PYTHONPATH": SRC}})
assert r.returncode == 0, "stage failed: read the traceback above"
'''


def payload() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        files = sorted((ROOT / "src/medsg").rglob("*.py")) + sorted((ROOT / "src/medsg/assets").glob("*.npz"))
        for f in files:
            z.write(f, f.relative_to(ROOT / "src"))
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("stage")
    ap.add_argument("--setup", type=Path, help="file with one shell command per line")
    ap.add_argument("--args", nargs="*", default=[])
    ap.add_argument("--ipynb", type=Path, help="also write a one-cell notebook to upload to Kaggle")
    a = ap.parse_args()
    if not (ROOT / f"src/medsg/stages/{a.stage}.py").exists():
        raise SystemExit(f"unknown stage {a.stage}")
    setup = [l.strip() for l in a.setup.read_text().splitlines()
             if l.strip() and not l.lstrip().startswith("#")] if a.setup else []
    pl = payload()                      # short lines: editors choke on one 160 kB line
    print("PAYLOAD = (\n" + "\n".join(f'    "{pl[i:i + 100]}"' for i in range(0, len(pl), 100)) + "\n)")
    print(TEMPLATE.format(stage=a.stage, setup=setup, args=a.args))
    if a.ipynb:
        import contextlib, json
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            pl = payload()
            print("PAYLOAD = (\n" + "\n".join(f'    "{pl[i:i + 100]}"' for i in range(0, len(pl), 100)) + "\n)")
            print(TEMPLATE.format(stage=a.stage, setup=setup, args=a.args))
        nb = {"cells": [{"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
                         "source": buf.getvalue().splitlines(keepends=True)}],
              "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                           "language_info": {"name": "python"}},
              "nbformat": 4, "nbformat_minor": 5}
        a.ipynb.write_text(json.dumps(nb, indent=1))


if __name__ == "__main__":
    main()
